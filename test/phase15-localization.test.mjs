import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import fsSync from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

import { runUpstream } from '../src/core/upstream.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const CLI = path.join(ROOT, 'bin', 'sdd-kit.mjs');

const LEGACY_ENGLISH = {
  'src/core/update.mjs': [/\bRestart \$\{label\}/, /\bOpen a new \$\{label\} session/],
  'src/register.mjs': [
    /Delegate directly to upstream/,
    /Repository root directory \(defaults/,
    /One of: setup, status/,
    /Explicit opt-in for action/,
    /For action /,
    /Override the Spec Kit extension/,
    /Visible SkillSummary\[\]/,
    /Thin read-mostly bridge/,
    /Spec Kit feature folder under specs/,
    /Spec Kit bug slug under/,
  ],
  'src/core/upstream.mjs': [/extension source not found at/, /cannot read extension manifest at/],
  'src/core/marker.mjs': [/clearHostMarker requires an explicit host/, /unknown host:/],
  'src/core/reload.mjs': [/unknown host:/, /unknown change layer:/],
  'src/core/host-capabilities.mjs': [/HOST_CAPABILITIES key mismatch:/, /invalid reloadPolicy for /],
  'scripts/verify-upstream.mjs': [
    /environment unavailable/,
    /Upstream contract verification/,
    /Status: \$\{report\.status\}/,
    /Version bound: declared/,
    /Kept: \$\{report\.tmpDir\}/,
    /not found on PATH/,
    /unparsable output/,
    /events registered once/,
    /contract check\(s\) failed/,
    /the installed .* is below/,
    /specify is not installed/,
  ],
  'src/core/bridge.mjs': [
    /Living Specs Index/,
    /Auto-generated by/,
    /In Progress \(/,
    /\| Feature \| Status \| Spec \| Plan \|/,
    /\*\(none\)\*/,
  ],
};

test('T104: legacy English user-facing prose is gone from production sources', () => {
  for (const [relative, patterns] of Object.entries(LEGACY_ENGLISH)) {
    const source = fsSyncRead(path.join(ROOT, relative));
    for (const pattern of patterns) {
      assert.doesNotMatch(source, pattern, `${relative} still contains ${pattern}`);
    }
  }
});

test('T104: a host-key invariant reached through the CLI is explained in Chinese', async () => {
  const repo = await fs.mkdtemp(path.join(os.tmpdir(), 'sdd-p15-locale-cli-'));
  const cli = spawnSync(process.execPath, [
    CLI, 'guidance', '--clear-marker', '--host', 'nope', '--cwd', repo, '--json',
  ], { cwd: ROOT, encoding: 'utf8', timeout: 10_000 });
  const json = JSON.parse(cli.stdout);
  assert.equal(json.status, 'error');
  assert.match(json.message, /未知.*宿主/);
  assert.match(json.fix, /可用宿主/);
});

test('T104: generated specs index uses Chinese status and column headings', async () => {
  const repo = await fs.mkdtemp(path.join(os.tmpdir(), 'sdd-p15-locale-index-'));
  const feature = path.join(repo, 'specs', '001-user-auth');
  await fs.mkdir(feature, { recursive: true });
  await fs.writeFile(path.join(feature, 'spec.md'), '# spec\n', 'utf8');
  await fs.writeFile(path.join(feature, 'plan.md'), '# plan\n', 'utf8');
  await fs.writeFile(path.join(feature, 'tasks.md'), '- [ ] T001 pending\n', 'utf8');
  const cli = spawnSync(process.execPath, [CLI, 'bridge', '--action', 'sync_index', '--cwd', repo, '--json'], {
    cwd: ROOT,
    encoding: 'utf8',
    timeout: 10_000,
  });
  assert.equal(cli.status, 0, cli.stdout);
  const index = await fs.readFile(path.join(repo, 'specs', 'INDEX.md'), 'utf8');
  assert.match(index, /规格索引/);
  assert.match(index, /进行中/);
  assert.match(index, /功能/);
  assert.doesNotMatch(index, /Living Specs Index/);
});

test('T104: upstream extension-path failures are explained in Chinese', async () => {
  const repo = await fs.mkdtemp(path.join(os.tmpdir(), 'sdd-p15-locale-upstream-'));
  const missing = path.join(repo, 'nope');
  const result = await runUpstream({ action: 'install_hooks_ext', cwd: repo, extensionDir: missing }, async () => ({
    ok: true,
    code: 0,
    stdout: '',
    stderr: '',
  }));
  assert.equal(result.ok, false);
  assert.match(result.error, /扩展源目录不存在/);
});

function fsSyncRead(file) {
  // Synchronous read keeps the static guard simple and fails loudly on typos.
  return requireFs().readFileSync(file, 'utf8');
}

function requireFs() {
  return fsSync;
}
